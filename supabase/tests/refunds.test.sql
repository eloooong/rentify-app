begin;
create extension if not exists pgtap with schema extensions;
set local search_path=public,extensions;
select no_plan();
select ok(relrowsecurity,'Refund ledger RLS enabled') from pg_class where oid='public.refund_attempts'::regclass;
select ok(not has_table_privilege('authenticated','public.refund_attempts','SELECT'),'No private ledger client reads');
select ok(not has_table_privilege('service_role','public.refund_attempts','UPDATE'),'Worker writes require validated RPCs');
select ok(has_function_privilege('authenticated','public.cancel_paid_booking(uuid,text)','EXECUTE'),'Signed-in cancellation entry point');
select ok(has_function_privilege('authenticated','public.get_booking_refunds(uuid)','EXECUTE'),'Participant status entry point');
select ok(not has_function_privilege('anon','public.cancel_paid_booking(uuid,text)','EXECUTE'),'Anonymous cancellation denied');
select ok(not has_function_privilege('authenticated','public.queue_receipt_refund(uuid)','EXECUTE'),'Clients cannot choose refund receipt or amount');
select ok(not has_function_privilege('authenticated','public.claim_refund_work(uuid)','EXECUTE'),'Worker leases private');
select ok(not has_function_privilege('authenticated','public.sync_refund(uuid,uuid,jsonb)','EXECUTE'),'Clients cannot mark refunded');
select ok(not has_function_privilege('authenticated','public.start_refund_creation(uuid,uuid)','EXECUTE'),'Clients cannot submit money movement');
select ok(not has_function_privilege('authenticated','public.fail_refund_work(uuid,uuid,text)','EXECUTE'),'Clients cannot release reservations');
select ok(not has_function_privilege('authenticated','public.refund_payload(public.bookings)','EXECUTE'),'Payload helper private');
select ok(not has_function_privilege('authenticated','public.paid_cancellation_allowed(public.bookings,uuid,timestamptz)','EXECUTE'),'Eligibility helper private');
select ok(has_function_privilege('service_role','public.sync_refund(uuid,uuid,jsonb)','EXECUTE'),'Trusted worker persists verified result');
grant select,insert,update,delete on public.refund_attempts to authenticated,anon;
set local role authenticated;
select is((select count(*) from public.refund_attempts),0::bigint,'Accidental grant cannot bypass deny-all RLS');
select throws_ok($$insert into public.refund_attempts(receipt_id,amount,generation) values(gen_random_uuid(),100,1)$$,'42501',null::text,'Accidental write grant cannot forge refunds');
select throws_ok($$select public.sync_refund(gen_random_uuid(),gen_random_uuid(),'{}')$$,'42501',null::text,'Forged success denied');
select throws_ok($$select public.cancel_paid_booking(gen_random_uuid(),'Changed plans')$$,'42501','profile_required','Missing active identity denied');
select throws_ok($$select public.get_booking_refunds(gen_random_uuid())$$,'P0001','not_found','No participant data leak');
reset role;
select * from finish();
rollback;
